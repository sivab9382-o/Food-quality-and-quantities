export function findRecipesForIngredients(ingredientList) {
  if (!ingredientList || ingredientList.length === 0) return RESCUE_RECIPES.slice(0, 3);
  
  const lowerList = ingredientList.map(i => i.toLowerCase().trim());
  const matches = RESCUE_RECIPES.filter(recipe => {
    return recipe.matchKeywords.some(keyword => {
      return lowerList.some(userItem => userItem.includes(keyword) || keyword.includes(userItem));
    });
  });

  return matches.length > 0 ? matches : RESCUE_RECIPES.slice(0, 3);
}
